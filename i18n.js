const SUPPORTED_LANGS = Object.keys(I18N);
function detectDefaultLang() {
  try {
    const saved = localStorage.getItem("taqsna_lang");
    if (saved && I18N[saved]) return saved;
  } catch (e) {}
  const nav = (navigator.language || "ar").slice(0, 2).toLowerCase();
  return I18N[nav] ? nav : "ar";
}
